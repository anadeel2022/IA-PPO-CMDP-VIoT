#!/usr/bin/env python3
"""Validate one VIoT experiment run before it is used in a manuscript.

The validator checks completeness, duplicate task rows, deterministic seed
bookkeeping, held-out evaluation counts, finite core metrics, intent-switch
censoring, and recorded failures. It writes both JSON and Markdown reports.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

CORE_METRICS = [
    "weighted_violation_mean",
    "weighted_violation_cvar95",
    "blocking_mean",
    "interruption_mean",
    "delay_mean_ms",
    "throughput_mean_mbps",
    "fairness_mean",
    "service_success_rate_mean",
]
KEY = ["intent", "scenario", "seed", "scheme"]


def _finite_fraction(series: pd.Series) -> float:
    numeric = pd.to_numeric(series, errors="coerce").to_numpy(dtype=float)
    return float(np.isfinite(numeric).mean()) if numeric.size else 0.0


def validate(run_dir: Path) -> dict[str, Any]:
    errors: list[str] = []
    warnings: list[str] = []
    checks: dict[str, Any] = {}
    terminal_drain_active = False

    manifest_path = run_dir / "manifest.json"
    seed_path = run_dir / "agentic_seed_summary.csv"
    checkpoint_path = run_dir / "_resume_checkpoint.csv"
    failures_path = run_dir / "failures.log"

    if not manifest_path.exists():
        errors.append("manifest.json is missing.")
        manifest: dict[str, Any] = {}
    else:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))

    data_path = seed_path if seed_path.exists() else checkpoint_path
    if not data_path.exists():
        errors.append("Neither agentic_seed_summary.csv nor _resume_checkpoint.csv exists.")
        df = pd.DataFrame()
    else:
        df = pd.read_csv(data_path)

    expected = 0
    if manifest:
        expected = (
            len(manifest.get("seeds", []))
            * len(manifest.get("schemes", []))
            * len(manifest.get("intents", []))
            * len(manifest.get("scenarios", []))
        )
    checks["expected_tasks"] = int(expected)
    checks["observed_tasks"] = int(len(df))
    if expected and len(df) != expected:
        errors.append(f"Incomplete task grid: expected {expected} rows, found {len(df)}.")

    if not df.empty:
        missing_key = [c for c in KEY if c not in df.columns]
        if missing_key:
            errors.append(f"Missing task-key columns: {missing_key}.")
        else:
            duplicates = int(df.duplicated(KEY).sum())
            checks["duplicate_task_rows"] = duplicates
            if duplicates:
                errors.append(f"Found {duplicates} duplicate intent/scenario/seed/scheme rows.")

        revision = str(manifest.get("runner_revision", ""))
        checks["runner_revision"] = revision
        if not (revision.startswith("submission_audit_v1") or revision.startswith("request_level_multichannel_v3") or revision.startswith("request_level_shielded_v4") or revision.startswith("request_level_universal_v4_3") or revision.startswith("request_level_universal_v4_4")):
            errors.append("The run was not generated by a supported corrected runner revision.")
        if revision.startswith(("request_level_multichannel_v3", "request_level_shielded_v4", "request_level_universal_v4_3", "request_level_universal_v4_4")):
            action_model = manifest.get("action_model", {})
            checks["request_level_accounting"] = bool(manifest.get("request_level_accounting", False))
            checks["action_model_n_actions"] = action_model.get("n_actions")
            if not bool(manifest.get("request_level_accounting", False)):
                errors.append("Request-level accounting is not enabled in the manifest.")
            if int(action_model.get("n_actions", 0) or 0) != 20:
                errors.append("The corrected candidate-mode action space should contain 20 actions.")

        for seed_col in ("env_seed", "evaluation_seed", "policy_seed"):
            if seed_col not in df.columns:
                errors.append(f"Missing {seed_col}; matched-seed provenance cannot be verified.")

        context_cols = ["intent", "scenario", "seed"]
        if all(c in df.columns for c in context_cols + ["env_seed"]):
            bad = df.groupby(context_cols, dropna=False)["env_seed"].nunique(dropna=False)
            n_bad = int((bad != 1).sum())
            checks["contexts_with_nonshared_environment_seed"] = n_bad
            if n_bad:
                errors.append(f"Environment seed is not shared across schemes in {n_bad} context(s).")

        if all(c in df.columns for c in context_cols + ["evaluation_seed"]):
            bad = df.groupby(context_cols, dropna=False)["evaluation_seed"].nunique(dropna=False)
            n_bad = int((bad != 1).sum())
            checks["contexts_with_nonshared_evaluation_seed"] = n_bad
            if n_bad:
                errors.append(f"Evaluation seed is not shared across schemes in {n_bad} context(s).")

        if "episodes" in df.columns and manifest:
            eval_episodes = int(manifest.get("eval_episodes", -1))
            episode_values = pd.to_numeric(df["episodes"], errors="coerce")
            n_bad = int((episode_values != eval_episodes).sum())
            checks["rows_with_wrong_evaluation_episode_count"] = n_bad
            if n_bad:
                errors.append(
                    f"{n_bad} row(s) do not report the manifest held-out evaluation count ({eval_episodes})."
                )

        if revision.startswith("request_level_universal_v4_4EC300"):
            train_steps = int(manifest.get("training_steps", -1))
            eval_steps = int(manifest.get("evaluation_steps", manifest.get("steps", -1)))
            checks["training_steps"] = train_steps
            checks["evaluation_steps"] = eval_steps
            if train_steps != 150:
                errors.append(f"Causal300 protocol requires 150 training steps, found {train_steps}.")
            if eval_steps != 300:
                errors.append(f"Causal300 protocol requires 300 evaluation steps, found {eval_steps}.")
            for col, expected in (("training_steps", train_steps), ("evaluation_steps", eval_steps)):
                if col not in df.columns:
                    errors.append(f"Causal300 run is missing row-level {col}.")
                else:
                    vals = pd.to_numeric(df[col], errors="coerce")
                    bad = int((vals != expected).sum())
                    checks[f"rows_with_wrong_{col}"] = bad
                    if bad:
                        errors.append(f"{bad} row(s) do not match manifest {col}={expected}.")
            if "unfinished_rate_mean" not in df.columns:
                errors.append("Causal300 run is missing unfinished_rate_mean.")
            elif _finite_fraction(df["unfinished_rate_mean"]) < 1.0:
                errors.append("Causal300 unfinished_rate_mean contains non-finite values.")

            drain_steps = int(manifest.get("terminal_drain_steps", 0) or 0)
            terminal_drain_active = drain_steps > 0
            checks["terminal_drain_steps"] = drain_steps
            checks["terminal_drain_sensitivity_mode"] = bool(terminal_drain_active)
            if drain_steps > 0:
                auto_extend = bool(manifest.get("terminal_drain_auto_extend", False))
                max_drain_steps = int(manifest.get("terminal_drain_max_steps", drain_steps) or drain_steps)
                checks["terminal_drain_auto_extend"] = auto_extend
                checks["terminal_drain_max_steps"] = max_drain_steps
                checks["effective_environment_steps"] = int(manifest.get("effective_environment_steps", eval_steps + max_drain_steps))
                if drain_steps < 250:
                    warnings.append(
                        f"Terminal-drain minimum follow-up is only {drain_steps} steps; the nominal best-effort deadline is 250 steps."
                    )
                for col in (
                    "right_censored_rate_mean", "measurement_right_censored_rate_mean",
                    "measurement_unfinished_rate_mean", "measurement_service_success_rate_mean",
                    "measurement_deadline_exposure_mean",
                ):
                    if col not in df.columns:
                        errors.append(f"Terminal-drain run is missing {col}.")
                    elif _finite_fraction(df[col]) < 1.0:
                        errors.append(f"Terminal-drain metric {col} contains non-finite values.")
                if "right_censored_rate_mean" in df.columns:
                    x = pd.to_numeric(df["right_censored_rate_mean"], errors="coerce").to_numpy(dtype=float)
                    max_censored = float(np.nanmax(x)) if np.isfinite(x).any() else math.inf
                    checks["terminal_right_censored_rate_max"] = max_censored
                    if not np.isfinite(max_censored) or max_censored > 1e-12:
                        errors.append(
                            f"Terminal-drain sensitivity still contains right-censored requests; maximum rate is {max_censored}."
                        )
                if auto_extend:
                    for col in ("terminal_drain_actual_steps_mean", "terminal_drain_actual_steps_max",
                                "terminal_drain_extension_steps_mean", "terminal_drain_extension_steps_max",
                                "max_realized_device_deadline_steps_max"):
                        if col not in df.columns:
                            errors.append(f"Adaptive terminal-drain run is missing {col}.")
                        elif _finite_fraction(df[col]) < 1.0:
                            errors.append(f"Adaptive terminal-drain metric {col} contains non-finite values.")
                    if "terminal_drain_actual_steps_max" in df.columns:
                        actual = pd.to_numeric(df["terminal_drain_actual_steps_max"], errors="coerce").to_numpy(dtype=float)
                        max_actual = float(np.nanmax(actual)) if np.isfinite(actual).any() else math.inf
                        checks["terminal_drain_actual_steps_max"] = max_actual
                        if not np.isfinite(max_actual) or max_actual > max_drain_steps + 1e-9:
                            errors.append(
                                f"Adaptive terminal drain exceeded its configured safety cap: observed {max_actual}, cap {max_drain_steps}."
                            )

        for col in CORE_METRICS:
            if col not in df.columns:
                errors.append(f"Core metric {col} is missing.")
                continue
            frac = _finite_fraction(df[col])
            checks[f"finite_fraction::{col}"] = frac
            if frac < 1.0:
                errors.append(f"Core metric {col} contains non-finite values (finite fraction {frac:.3f}).")

        if "request_conservation_error_max_abs" in df.columns:
            x = pd.to_numeric(df["request_conservation_error_max_abs"], errors="coerce")
            max_err = float(np.nanmax(np.abs(x.to_numpy(dtype=float)))) if np.isfinite(x.to_numpy(dtype=float)).any() else math.inf
            checks["request_conservation_error_max_abs"] = max_err
            if not np.isfinite(max_err) or max_err > 1e-9:
                errors.append(f"Request accounting is not conservative; maximum absolute error is {max_err}.")
        elif revision.startswith(("request_level_multichannel_v3", "request_level_shielded_v4", "request_level_universal_v4_3", "request_level_universal_v4_4")):
            errors.append("Request-level run is missing request_conservation_error_max_abs.")

        switch_active = False
        if "intent_switch_active" in df.columns:
            switch_values = pd.to_numeric(df["intent_switch_active"], errors="coerce")
            switch_active = bool((switch_values > 0).any())
        checks["intent_switch_active"] = switch_active

        if switch_active and not terminal_drain_active:
            for col in ("post_switch_violation_mean", "switch_adaptation_time_steps", "switch_adaptation_success"):
                if col not in df.columns:
                    errors.append(f"Switch run is missing {col}.")
                elif _finite_fraction(df[col]) < 1.0:
                    errors.append(f"Switch metric {col} contains non-finite values.")
            if "switch_adaptation_success" in df.columns:
                # Each seed-summary row aggregates multiple held-out evaluation
                # episodes, so this field is an adaptation-success rate rather
                # than a single binary episode outcome. Fractional values are
                # therefore valid as long as they remain in the unit interval.
                x = pd.to_numeric(df["switch_adaptation_success"], errors="coerce")
                finite = np.isfinite(x.to_numpy(dtype=float))
                outside = finite & ((x.to_numpy(dtype=float) < -1e-12) | (x.to_numpy(dtype=float) > 1.0 + 1e-12))
                invalid = int(outside.sum())
                checks["switch_adaptation_success_min"] = float(np.nanmin(x)) if finite.any() else None
                checks["switch_adaptation_success_max"] = float(np.nanmax(x)) if finite.any() else None
                if invalid:
                    errors.append(
                        f"switch_adaptation_success has {invalid} value(s) outside [0,1]."
                    )
                elif finite.any() and float(np.nanmax(x)) <= 0.0:
                    warnings.append(
                        "No held-out episode reached the declared post-switch settling band; review adaptation references and tolerance before final reporting."
                    )
            if "switch_adaptation_time_steps" in df.columns and manifest:
                x = pd.to_numeric(df["switch_adaptation_time_steps"], errors="coerce")
                steps = int(manifest.get("steps", 0))
                switch_frac = float(manifest.get("intent_switch_frac", 0.5))
                post_horizon = max(1, steps - int(round(steps * switch_frac)))
                too_large = int((x > post_horizon + 1e-9).sum())
                negative = int((x < 0).sum())
                checks["post_switch_horizon_steps"] = post_horizon
                if too_large or negative:
                    errors.append(
                        f"Adaptation time is outside [0,{post_horizon}] in {too_large + negative} row(s)."
                    )
        elif switch_active and terminal_drain_active:
            checks["switch_behavior_diagnostics_validation"] = "SKIPPED_BY_DESIGN_FOR_ACCOUNTING_SENSITIVITY"


        for col in (
            "feasibility_filter_active_rate", "feasibility_filtered_action_fraction",
            "shield_filter_active_rate", "shield_filtered_action_fraction", "shield_override_rate_mean"
        ):
            if col in df.columns:
                x = pd.to_numeric(df[col], errors="coerce").to_numpy(dtype=float)
                finite = np.isfinite(x)
                invalid = finite & ((x < -1e-12) | (x > 1.0 + 1e-12))
                checks[f"range::{col}"] = [float(np.nanmin(x)) if finite.any() else None, float(np.nanmax(x)) if finite.any() else None]
                if int(invalid.sum()):
                    errors.append(f"{col} contains values outside [0,1].")

        if bool(manifest.get("multi_intent_training", False)) and "policy_fingerprint" in df.columns:
            learned = df[df["policy_fingerprint"].fillna("").astype(str).str.len() > 0].copy()
            if not learned.empty:
                nuniq = learned.groupby(["seed", "scheme"], dropna=False)["policy_fingerprint"].nunique(dropna=False)
                bad = int((nuniq != 1).sum())
                checks["universal_policy_groups_with_multiple_fingerprints"] = bad
                if bad:
                    errors.append(
                        f"Universal training produced multiple policy fingerprints in {bad} seed/scheme group(s); evaluation contexts are not using one frozen policy."
                    )
            else:
                warnings.append("Universal training is enabled but no learned-policy fingerprints were recorded.")

        if revision.startswith("request_level_universal_v4_4EC300") and "policy_fingerprint" in df.columns:
            causal_name = "Intent-PPO-CMDP-FullPolicy-NoShield"
            full_name = "Intent-PPO-CMDP"
            if causal_name in set(df.get("scheme", pd.Series(dtype=str)).astype(str)):
                key = ["intent", "scenario", "seed"]
                a = df[df.scheme == full_name][key + ["policy_fingerprint"]].rename(columns={"policy_fingerprint": "fp_full"})
                b = df[df.scheme == causal_name][key + ["policy_fingerprint"]].rename(columns={"policy_fingerprint": "fp_causal"})
                m = a.merge(b, on=key, how="inner")
                mismatch = int((m.fp_full.astype(str) != m.fp_causal.astype(str)).sum()) if not m.empty else 1
                checks["causal_same_checkpoint_pairs"] = int(len(m))
                checks["causal_same_checkpoint_mismatches"] = mismatch
                if m.empty or mismatch:
                    errors.append("FullPolicy-NoShield does not exactly reuse the Full IA checkpoint in every matched context.")

        if switch_active and not terminal_drain_active:
            for col in ("intent_action_shift_l1", "intent_mode_shift_l1"):
                if col in df.columns:
                    frac = _finite_fraction(df[col])
                    checks[f"finite_fraction::{col}"] = frac
                    if frac < 1.0:
                        errors.append(f"Switch behavior metric {col} contains non-finite values.")

        # Policy-distribution diagnostics are properties of the 300-step deployment
        # window and are already validated in the frozen primary final run. The
        # terminal-drain sensitivity changes only terminal accounting after arrivals
        # stop, so it must not fail because those secondary diagnostics are not
        # propagated into the terminal summary rows. Checkpoint identity is still
        # verified above and all terminal request/accounting metrics remain strict.
        if terminal_drain_active:
            checks["policy_distribution_diagnostics_scope"] = "primary_300_step_run_only"
            checks["policy_distribution_diagnostics_revalidated_in_terminal_drain"] = False
        elif revision.startswith("request_level_universal_v4_4") and "policy_fingerprint" in df.columns:
            learned = df[df["policy_fingerprint"].fillna("").astype(str).str.len() > 0].copy()
            for col in (
                "counterfactual_intent_policy_l1",
                "counterfactual_mode_policy_l1",
                "counterfactual_argmax_change_rate",
                "frozen_policy_entropy_norm",
            ):
                if col not in df.columns:
                    errors.append(f"V4.4 run is missing {col}.")
                    continue
                x = pd.to_numeric(learned[col], errors="coerce")
                frac = float(np.isfinite(x.to_numpy(dtype=float)).mean()) if len(x) else 1.0
                checks[f"finite_fraction::{col}::learned"] = frac
                if frac < 1.0:
                    errors.append(f"V4.4 learned-policy metric {col} contains non-finite values.")

        # V4.4E stochastic frozen-policy evaluation diagnostics.
        eval_mode = str(manifest.get("evaluation_action_mode", "greedy")).lower()
        checks["evaluation_action_mode"] = eval_mode
        if eval_mode == "stochastic" and not terminal_drain_active:
            learned = df[df.get("policy_fingerprint", "").fillna("").astype(str).str.len() > 0].copy() if "policy_fingerprint" in df.columns else pd.DataFrame()
            if "evaluation_action_sampling_seed" not in df.columns:
                errors.append("Stochastic evaluation is missing evaluation_action_sampling_seed.")
            elif all(c in df.columns for c in context_cols + ["evaluation_action_sampling_seed"]):
                bad = df.groupby(context_cols, dropna=False)["evaluation_action_sampling_seed"].nunique(dropna=False)
                n_bad = int((bad != 1).sum())
                checks["contexts_with_nonshared_action_sampling_seed"] = n_bad
                if n_bad:
                    errors.append(f"Action-sampling seed is not shared across schemes in {n_bad} context(s).")
            required_stochastic = [
                "pre_mask_reject_probability",
                "feasible_reject_probability",
                "pre_mask_unsafe_probability_mass",
                "shield_filtered_probability_mass",
                "actual_shield_prevention_rate",
                "stochastic_action_entropy",
            ]
            for col in required_stochastic:
                if col not in df.columns:
                    errors.append(f"V4.4E stochastic run is missing {col}.")
                    continue
                x = pd.to_numeric(learned[col], errors="coerce").to_numpy(dtype=float) if len(learned) else np.array([], dtype=float)
                finite = np.isfinite(x)
                frac = float(finite.mean()) if x.size else 1.0
                checks[f"finite_fraction::{col}::learned"] = frac
                if frac < 1.0:
                    errors.append(f"V4.4E learned-policy metric {col} contains non-finite values.")
                if finite.any() and col != "stochastic_action_entropy_nats":
                    outside = finite & ((x < -1e-12) | (x > 1.0 + 1e-12))
                    if int(outside.sum()):
                        errors.append(f"{col} contains values outside [0,1].")
            mode_cols = [f"policy_mode_prob_{name}" for name in ("defer", "grant", "protect", "coexist", "reject")]
            missing_modes = [c for c in mode_cols if c not in df.columns]
            if missing_modes:
                errors.append(f"V4.4E stochastic run is missing deployment mode probabilities: {missing_modes}.")
            elif not learned.empty:
                vals = learned[mode_cols].apply(pd.to_numeric, errors="coerce").to_numpy(dtype=float)
                sums = np.nansum(vals, axis=1)
                max_err = float(np.nanmax(np.abs(sums - 1.0))) if sums.size else 0.0
                checks["deployment_mode_probability_sum_max_abs_error"] = max_err
                if max_err > 1e-6:
                    errors.append(f"Deployment mode probabilities do not sum to one; max absolute error {max_err}.")
        elif eval_mode == "stochastic" and terminal_drain_active:
            checks["stochastic_policy_diagnostics_validation"] = "SKIPPED_BY_DESIGN_FOR_ACCOUNTING_SENSITIVITY"
            warnings.append(
                "Terminal-drain sensitivity validates terminal accounting only; V4.4E policy-distribution diagnostics "
                "remain those already validated in the frozen 300-step primary run."
            )

    if failures_path.exists() and failures_path.read_text(encoding="utf-8").strip():
        errors.append("failures.log is non-empty.")

    if not (run_dir / "agentic_summary_aggregated.csv").exists():
        warnings.append("agentic_summary_aggregated.csv is absent; figure generation may be unavailable.")

    checks["seed_protocol"] = manifest.get("seed_protocol") if manifest else None
    return {
        "run_directory": str(run_dir.resolve()),
        "status": "PASS" if not errors else "FAIL",
        "errors": errors,
        "warnings": warnings,
        "checks": checks,
    }


def write_reports(run_dir: Path, report: dict[str, Any]) -> None:
    (run_dir / "submission_validation_report.json").write_text(
        json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    lines = [
        "# Submission validation report",
        "",
        f"Status: **{report['status']}**",
        "",
        f"Run directory: `{report['run_directory']}`",
        "",
        "## Errors",
    ]
    errors = report["errors"]
    lines.extend([f"- {x}" for x in errors] if errors else ["- None."])
    lines += ["", "## Warnings"]
    warnings = report["warnings"]
    lines.extend([f"- {x}" for x in warnings] if warnings else ["- None."])
    lines += ["", "## Checks"]
    for key, value in report["checks"].items():
        lines.append(f"- `{key}`: `{value}`")
    (run_dir / "submission_validation_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("run_dir", type=Path, help="Experiment output directory.")
    args = parser.parse_args()
    report = validate(args.run_dir)
    write_reports(args.run_dir, report)
    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0 if report["status"] == "PASS" else 2


if __name__ == "__main__":
    raise SystemExit(main())
